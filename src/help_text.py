def format_list(names):
    """Составить список команд с краткими описаниями.

    :param names: имена команд в порядке показа.
    :return: многострочный текст со столбцами "использование" и
        "описание".
    """
    width = max(len(HELP[name].usage) for name in names)
    lines = [LIST_TITLE]
    for name in names:
        entry = HELP[name]
        lines.append(
            INDENT + entry.usage.ljust(width) + COLUMN_GAP + entry.summary
        )
    return "\n".join(lines + ["", LIST_FOOTER])


def format_entry(name):
    """Составить подробную справку по одной команде.

    :param name: имя команды из HELP.
    :return: многострочный текст: использование, описание, ключи и
        примечания (пустые разделы пропускаются).
    """
    entry = HELP[name]
    lines = [entry.usage, INDENT + entry.summary]
    if entry.options:
        width = max(len(key) for key, _ in entry.options)
        lines += ["", OPTIONS_TITLE]
        lines += [
            INDENT + key.ljust(width) + COLUMN_GAP + text
            for key, text in entry.options
        ]
    if entry.notes:
        lines += ["", NOTES_TITLE]
        lines += [INDENT + note for note in entry.notes]
    return "\n".join(lines)
