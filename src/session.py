"""Состояние сеанса работы эмулятора."""


class Session:
    """Состояние одного сеанса: подключённая VFS.

    Объект передаётся обработчикам команд, чтобы они могли получить
    доступ к VFS. На следующих этапах здесь же появится текущий
    каталог.
    """

    def __init__(self, vfs=None):
        """Создать сеанс.

        :param vfs: объект Vfs или None, если VFS не подключена.
        """
        self.vfs = vfs
